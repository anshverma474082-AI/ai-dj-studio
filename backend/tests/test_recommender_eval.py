@pytest.mark.unit
def test_precision_counts_only_what_the_rail_actually_put_on_screen():
    relevant = {"t_a", "t_b", "t_c", "t_d", "t_e"}
    assert precision_at(["t_a", "t_b", "t_c", "t_d", "t_e"], relevant) == 1.0
    assert precision_at(["t_x", "t_y", "t_z", "t_w", "t_v"], relevant) == 0.0


@pytest.mark.unit
def test_a_short_rail_is_penalised_for_its_empty_slots():
    """Three good picks out of five slots is 0.6, not 1.0 — the denominator is the rail."""
    assert precision_at(["t_a", "t_b", "t_c"], {"t_a", "t_b", "t_c", "t_d"}) == pytest.approx(0.6)


