@pytest.mark.unit
def test_the_generated_dataset_is_the_same_twice():
    """A KPI number a reviewer cannot reproduce is a claim, not a measurement."""
    first_entries, first_signals = build_crowd()
    second_entries, second_signals = build_crowd()
    assert [s.track_id for s in first_signals] == [s.track_id for s in second_signals]
    assert [s.user_id for s in first_signals] == [s.user_id for s in second_signals]
    assert sorted(first_entries) == sorted(second_entries)


@pytest.mark.unit
def test_the_dataset_is_bigger_than_the_app_s_own_catalog():
    """Six records cannot produce a Precision@5 with any resolution: a rail of five is
    most of the catalog, so almost any ordering scores high."""
    entries, _ = build_crowd()
    assert len(entries) >= 20


@pytest.mark.unit
def test_every_listener_is_scored_on_records_the_model_never_saw():
    _, signals = build_crowd()
    train, test = split_signals(signals)
    trained = {(s.user_id, s.track_id) for s in train}
    assert not trained & {(s.user_id, s.track_id) for s in test}, "the split leaked"

    testers = {s.user_id for s in test}
    assert testers == {s.user_id for s in train}
    assert all(sum(1 for s in test if s.user_id == user) >= K for user in testers), (
        "a listener with fewer held-out records than the rail length can never reach 1.0"
    )


@pytest.mark.unit
def test_a_listeners_quirk_scene_never_repeats_their_crews_own_record():
    """The dataset rule that keeps the split clean, asserted on its own.

    Each listener's strong history is meant to be ten *distinct* records. It briefly was ten
    slots holding nine, because a quirk scene drawn from the same pool as the crew's affinity
    scenes could name a record the listener already had — and the duplicate then trained on
    one side of the positional split while being scored on the other. Asserting the history
    is distinct catches that directly, instead of leaving it to surface as a leak with a
    confusing message three functions away.
    """
    _, signals = build_crowd()
    per_listener: dict[str, list[str]] = {}
    for signal in signals:
        if signal.completed:
            per_listener.setdefault(signal.user_id, []).append(signal.track_id)

    assert len(per_listener) == 12
    for user, history in per_listener.items():
        assert len(set(history)) == len(history) == 10, f"{user}'s history repeats a record"


@pytest.mark.unit
def test_the_held_out_records_are_positive_signals_not_mere_exposure():
    """Grading a rail against records the listener sat through for four seconds would be
    measuring the room, not the taste."""
    _, signals = build_crowd()
    _, test = split_signals(signals)
    assert all(signal.liked or signal.completed for signal in test)


