@pytest.mark.unit
def test_the_engine_clears_the_kpi_target():
    report = evaluate(*build_crowd())
    assert report.precision >= 0.6, f"Precision@5 landed at {report.precision:.3f}"


@pytest.mark.unit
def test_the_blend_earns_the_word_hybrid():
    """Neither half alone, and nobody's-favourite-records alone, reaches what the blend does.

    Measured on this split: content alone 0.467, collaborative alone 0.583, popularity
    0.333, blend 0.717. The strict inequalities are the point — if one half could be dropped
    without moving the number, §6.3's hybrid would be decoration on a one-term model, and
    `main()` would print a table that says so instead of hiding it.
    """
    report = evaluate(*build_crowd())
    assert report.hybrid > report.content_only
    assert report.hybrid > report.cf_only
    assert report.hybrid > report.popularity
    assert report.hybrid > 0.0


@pytest.mark.unit
def test_the_baseline_that_knows_nobody_reaches_the_target():
    """Popularity is what the KPI would report if the model confused taste with loudness.

    Crews 0 and 3 share `house`, so the crowd's favourites are the same few records for
    everyone; holding that baseline under the target is what makes 0.717 a claim about the
    listener rather than about the catalog.
    """
    report = evaluate(*build_crowd())
    assert report.popularity < 0.6, f"popularity alone already clears the target: {report.popularity}"


@pytest.mark.unit
def test_the_rail_never_wastes_a_slot_on_a_record_the_listener_already_has():
    entries, signals = build_crowd()
    train, _ = split_signals(signals)
    for user in sorted({s.user_id for s in train}):
        rail = recommend(train, entries, user_id=user, limit=K)
        trained = {s.track_id for s in train if s.user_id == user}
        assert not trained & {item.track_id for item in rail.items}


